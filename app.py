# --- SIDEBAR CONTROLS ---
st.sidebar.header("Investment Settings")

horizon = st.sidebar.selectbox(
    "Investment Goal:",
    ['Short-Term Momentum (1 - 6 Months)', 'Long-Term Wealth Accumulation (1 - 10 Years SIP)']
)

budget = st.sidebar.number_input("Total Investment / Monthly Budget (PKR):", value=50000, step=5000)

years = st.sidebar.slider("Duration (Years):", min_value=1, max_value=10, value=5)

growth_option = st.sidebar.selectbox(
    "Market Growth Rate:",
    [('8% Growth Rate (Moderate)', 8.0),
     ('5% Growth Rate (Conservative)', 5.0),
     ('12% Growth Rate (Aggressive)', 12.0),
     ('Historical CAGR Auto', 0.0)]
)
chosen_growth = growth_option[1]

st.sidebar.markdown("---")
st.sidebar.subheader("Select Companies by Sector")

selected_dict = {}
for sector, comps in SECTOR_COMPANIES.items():
    with st.sidebar.expander(sector):
        for name, data in comps.items():
            if st.checkbox(f"{name} ({data['div_yield']}%)", key=name):
                selected_dict[name] = (data['symbol'], data['div_yield'])

run_clicked = st.sidebar.button("Generate Portfolio Prediction", type="primary")

# --- MAIN WINDOW LOGIC ---
if run_clicked:
    if not selected_dict:
        st.warning("kindly select atleast one company")
    else:
        with st.spinner("Analyzing market data across sectors. Please wait."):
            performance_data = []
            for name, (symbol, fixed_div) in selected_dict.items():
                ticker = yf.Ticker(symbol)
                df = ticker.history(period="1y")
                if df.empty or len(df) < 30:
                    continue

                latest_price = float(df['Close'].iloc[-1])
                ret_1m = ((latest_price / float(df['Close'].iloc[-22])) - 1) * 100 if len(df) >= 22 else 0.0
                ret_6m = ((latest_price / float(df['Close'].iloc[-132])) - 1) * 100 if len(df) >= 132 else ret_1m
                ret_1y = ((latest_price / float(df['Close'].iloc[0])) - 1) * 100
                rsi = RSIIndicator(close=df['Close'], window=14).rsi().iloc[-1]

                performance_data.append({
                    "Company": name,
                    "Price (PKR)": round(latest_price, 2),
                    "1M Return %": round(ret_1m, 2),
                    "6M Return %": round(ret_6m, 2),
                    "1Y Return %": round(ret_1y, 2),
                    "Dividend Yield %": fixed_div,
                    "RSI": round(rsi, 2)
                })

            perf_df = pd.DataFrame(performance_data)

            if perf_df.empty:
                st.error("data can't be fetched of selected company.")
            else:
                if 'Short-Term' in horizon:
                    st.subheader("Short-Term Momentum and Custom Portfolio Allocation")
                    st.dataframe(perf_df.set_index('Company'), use_container_width=True)

                    st.markdown("---")
                    st.subheader(f" Budget Allocation (Total Budget: {budget:,} PKR)")
                    alloc_per_stock = budget / len(perf_df)

                    alloc_list = []
                    for idx, row in perf_df.iterrows():
                        shares = int(alloc_per_stock // row['Price (PKR)'])
                        alloc_list.append({
                            "Company": row['Company'],
                            "Shares to Buy": shares,
                            "Price": row['Price (PKR)'],
                            "Estimated Investment": f"~{shares * row['Price (PKR)']:,.2f} PKR"
                        })
                    st.table(pd.DataFrame(alloc_list).set_index('Company'))
                    st.info("Short-Term Note: RSI par nazar rakhein. Agar RSI 70 se upar jaye toh profit book kar lein.")

                else:
                    st.subheader("Long-Term Wealth Accumulation & Custom SIP Prediction")
                    st.dataframe(perf_df.set_index('Company'), use_container_width=True)

                    total_months = years * 12
                    total_invested = budget * total_months
                    growth_rate = chosen_growth if chosen_growth > 0.0 else 10.0
                    monthly_rate = (growth_rate / 100) / 12

                    fv_capital = budget * (((1 + monthly_rate)**total_months - 1) / monthly_rate) * (1 + monthly_rate)
                    avg_div_yield = perf_df['Dividend Yield %'].mean()
                    total_dividends = total_invested * (avg_div_yield / 100) * (years / 2)
                    total_portfolio = fv_capital + total_dividends
                    net_profit = total_portfolio - total_invested

                    st.markdown("---")
                    st.subheader(f" Custom Portfolio SIP Forecast ({years} Years @ {growth_rate}% Annual Growth)")

                    col1, col2, col3 = st.columns(3)
                    col1.metric("Total Capital Invested", f"{total_invested:,.0f} PKR")
                    col2.metric("Projected Portfolio Value", f"{total_portfolio:,.0f} PKR", f"+{net_profit:,.0f} PKR Profit")
                    col3.metric("Estimated Cash Dividends", f"{total_dividends:,.0f} PKR", f"Avg {avg_div_yield:.2f}% Yield")

                    st.success(f" **Net Wealth Profit Forecast:** {net_profit:,.2f} PKR (+{(net_profit/total_invested)*100:.2f}% Total Return)")
else:
    st.info(" Select your investment goals and companies 'Click on Generate Portfolio Prediction'!")
